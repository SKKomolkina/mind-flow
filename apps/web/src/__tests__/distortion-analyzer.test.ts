
export const stemRussianWord = (word: string): string => {
  let w = word.toLowerCase().replace(/ё/g, 'е');

  const REFLEXIVE   = /ся$|сь$/;
  const ADJECTIVAL  = /ая$|ее$|ею$|еи$|ие$|ий$|их$|ые$|ый$|ых$|ое$|ою$|ую$|яя$|ями$|ыми$|ого$|его$|ому$|ему$/;
  const VERB        = /аю$|ет$|ете$|ем$|ут$|ют$|ешь$|у$|ю$|ла$|ло$|ли$|л$|ть$|нно$/;
  const NOUN        = /а$|ев$|ов$|е$|и$|ий$|ия$|ы$|ь$|ями$|ами$|ах$|о$|у$|ом$|ем$|ию$|ей$|ой$|иям$/;
  const DERIVATIONAL = /ост$|ость$/;

  w = w.replace(REFLEXIVE, '');
  w = w.replace(ADJECTIVAL, '');
  w = w.replace(VERB, '');
  w = w.replace(NOUN, '');
  w = w.replace(DERIVATIONAL, '');

  return w;
};

export const DISTORTION_MARKERS: Record<string, string[]> = {
  'Сверхобобщение':               ['всегд', 'никогд', 'вечн', 'постоянн', 'все', 'никт', 'кажд'],
  'Все или ничего':               ['плох', 'идеальн', 'ужасн', 'либ', 'ил', 'крайн'],
  'Негативный фильтр':            ['плох', 'ошибк', 'неудач', 'проблем'],
  'Обесценивание положительного': ['везл', 'пустяк', 'ничег', 'особен'],
  'Поспешные выводы':             ['точн', 'дума', 'счита', 'уверен'],
  'Катастрофизация':              ['кошмар', 'ужас', 'конец', 'умр', 'катастроф', 'невыносим'],
  'Эмоциональное обоснование':    ['чувству', 'кажет', 'ощуща', 'мн'],
  'Императивы':                   ['долж', 'обязан', 'над', 'необходим', 'прид'],
  'Ярлыки':                       ['неудачник', 'глуп', 'дурак', 'идиот', 'тупиц', 'слабак'],
  'Вина':                         ['вин', 'виноват'],
};

export const analyzeText = (text: string): string[] => {
  const tokens = text.toLowerCase().match(/[а-яё]+/g) ?? [];
  const stemmedWords = tokens.map(stemRussianWord);
  return Object.keys(DISTORTION_MARKERS).filter(name =>
    DISTORTION_MARKERS[name].some(marker => stemmedWords.includes(marker))
  );
};


describe('Стеммер: базовая нормализация', () => {
  test('замена ё→е выполняется до стемминга', () => {
    expect(stemRussianWord('всё')).not.toContain('ё');
  });

  test('"всегда" → "всегд"', () => {
    expect(stemRussianWord('всегда')).toBe('всегд');
  });

  test('"никогда" → "никогд"', () => {
    expect(stemRussianWord('никогда')).toBe('никогд');
  });

  test('"кошмар" — неизменяемое существительное сохраняется', () => {
    expect(stemRussianWord('кошмар')).toBe('кошмар');
  });

  test('"виноват" — краткое прилагательное сохраняется', () => {
    expect(stemRussianWord('виноват')).toBe('виноват');
  });

  test('"неудачник" — существительное сохраняется', () => {
    expect(stemRussianWord('неудачник')).toBe('неудачник');
  });

  test('"обязан" — краткое прилагательное сохраняется', () => {
    expect(stemRussianWord('обязан')).toBe('обязан');
  });
});


